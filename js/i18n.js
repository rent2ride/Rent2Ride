/**
 * Applique la langue sélectionnée aux éléments contenant data-i18n
 */
function applyLanguage(lang) {
  const currentLang = TRANSLATIONS[lang] ? lang : "fr";
  localStorage.setItem("rent2ride_lang", currentLang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const translation = TRANSLATIONS[currentLang][key];
    if (translation) {
      el.textContent = translation;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const translation = TRANSLATIONS[currentLang][key];
    if (translation) {
      el.placeholder = translation;
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === currentLang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("rent2ride_lang") || "fr";
  applyLanguage(savedLang);

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang");
      applyLanguage(lang);
    });
  });
});